#!/usr/bin/env node
// Generates shared/directus/schema.ts from the live ST8 Directus schema (directus-sdk-typegen).
//
//   pnpm generate:types
//
// Reading the schema (/collections, /fields, /relations) needs the admin DIRECTUS_TOKEN from .env, so this is a
// scripts-only use of that token. The app itself reads only public data and never sees it. Read-only: nothing is
// written to Directus. Re-run it after a schema change (the podcast, core services and search fields land from
// scripts/directus/search-services-podcast-setup.mjs).

import { spawnSync } from 'node:child_process'
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const ROOT = resolve(dirname(fileURLToPath(import.meta.url)), '..')
const OUT = join(ROOT, 'shared/directus/schema.ts')
const url = (process.env.DIRECTUS_URL || '').replace(/\/$/, '')
const token = process.env.DIRECTUS_TOKEN

if (!url || !token) {
  console.error('generate:types: DIRECTUS_URL and DIRECTUS_TOKEN (admin, scripts only) must be set in .env.')
  process.exit(1)
}

const run = spawnSync(join(ROOT, 'node_modules/.bin/directus-sdk-typegen'), ['-u', url, '-t', token, '-o', OUT], {
  cwd: ROOT,
  stdio: 'inherit',
})
if (run.status !== 0) process.exit(run.status ?? 1)

const header = `// Generated by \`pnpm generate:types\` from ${url} on ${new Date().toISOString().slice(0, 10)}. Do not edit.\n/* eslint-disable */\n\n`
writeFileSync(OUT, header + readFileSync(OUT, 'utf8'))
console.log(`generate:types: wrote ${OUT.replace(`${ROOT}/`, '')}`)
